#!/bin/bash
# resolve-meta-closure.sh; write packages/.meta-closure.txt as the
# fully-resolved Arch transitive closure of shedos-meta's depends.
#
# Without this, render-meta-depends.sh names only the broad-list
# roots; install-time pacstrap then picks alphabetical defaults for
# any unpinned virtual provider; same trap that broke the live-ISO
# build (jack → jack2, pipewire-session-manager → pipewire-media-session).
#
# Closure input: packages/official/*.txt (broad Arch + multilib roots).
# AUR + shedos-* names are filtered from the resolution input; they
# aren't in pacman repos at script-run time; and re-applied verbatim
# by render-meta-depends.sh. Any AUR-introduced transitive Arch dep
# that isn't already in the broad closure gets pulled in by pacman at
# install time; that's a small remaining surface but keeps the script
# robust against stale files in the channel.
#
# A closure name the release manifest also names is written down with a
# marker: the channel serves that package, not Arch, and the renderer emits
# the manifest's pinned form for it instead of a bare Arch name.
#
# Requires root for `pacman -Sy` (db sync). Runs in an isolated
# tempdir so the host /var/lib/pacman is untouched. Locally:
# `sudo tools/resolve-meta-closure.sh`. In CI it is the meta workflow's
# closure job, which is where the root container already is.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=tools/lib-meta.sh
source "$SCRIPT_DIR/lib-meta.sh"
PACKAGES_DIR=$META_PACKAGES
OUTPUT_FILE=$META_CLOSURE

if [[ $EUID -ne 0 ]]; then
    echo "ERROR: must be run as root — pacman -Sy syncs the db." >&2
    echo "       Run: sudo $0" >&2
    exit 1
fi

echo "=========================================="
echo "Resolving shedos-meta Arch closure"
echo "=========================================="

declare -A aur_set
while IFS= read -r p; do
    [[ -n "$p" ]] && aur_set[$p]=1
done < <(list_names "$PACKAGES_DIR/aur.txt" | LC_ALL=C sort -u)

# Every package the release manifest names is served by the channel. Those
# that are also Arch roots stay roots — resolving Arch's cage is how cage's
# own dependencies reach the closure — and get their marker below. The rest
# have no Arch package to resolve at all.
declare -A channel_set
while IFS=$'\t' read -r name _ _; do
    [[ -n "$name" ]] && channel_set[$name]=1
done < <(manifest_entries "$META_MANIFEST")
(( ${#channel_set[@]} > 0 )) || { echo "ERROR: $META_MANIFEST names no packages." >&2; exit 1; }

# installer.txt is the live-ISO Calamares dep list (kf6-*, qt5-*,
# etc.); those libs only need to exist in the live env so Calamares
# can run, NOT on the installed system. Exclude that file from the
# meta closure so its entries don't bloat shedos-meta. The file still
# feeds the ISO build's package list.
ARCH_ROOTS=()
while IFS= read -r pkg; do
    [[ -z "$pkg" || "$pkg" =~ ^# ]] && continue
    [[ "$pkg" == shedos-* ]] && continue
    [[ -n ${aur_set[$pkg]:-} ]] && continue
    ARCH_ROOTS+=("$pkg")
done < <(
    find "$PACKAGES_DIR/official" -maxdepth 1 -type f -name '*.txt' \
        ! -name 'installer.txt' -print0 \
        | xargs -0 grep -hEv '^\s*(#|$)' \
        | LC_ALL=C sort -u
)

mapfile -t ARCH_ROOTS < <(printf '%s\n' "${ARCH_ROOTS[@]}" | LC_ALL=C sort -u)
echo "Arch roots: ${#ARCH_ROOTS[@]} packages"

TMPDIR=$(mktemp -d)
trap "rm -rf $TMPDIR" EXIT
mkdir -p "$TMPDIR/db"

cat > "$TMPDIR/pacman.conf" << 'EOF'
[options]
HoldPkg     = pacman glibc
Architecture = x86_64
SigLevel    = Never
LocalFileSigLevel = Optional

[core]
Include = /etc/pacman.d/mirrorlist

[extra]
Include = /etc/pacman.d/mirrorlist

[multilib]
Include = /etc/pacman.d/mirrorlist
EOF

# expac takes a config and no --dbpath, so the isolated database has to be
# named in the file rather than on the command line. It belongs in [options];
# appended to the end it lands inside the last repository section and pacman
# says so. pacman is given both and they say the same thing.
sed -i "/^\[options\]/a DBPath = $TMPDIR/db" "$TMPDIR/pacman.conf"

echo "Syncing pacman databases into $TMPDIR/db ..."
pacman -Sy --noconfirm \
    --dbpath "$TMPDIR/db" \
    --config "$TMPDIR/pacman.conf" >/dev/null

echo "Resolving Arch transitive closure ..."
pacman -Sp --noconfirm \
    --dbpath "$TMPDIR/db" \
    --config "$TMPDIR/pacman.conf" \
    --print-format '%n' \
    "${ARCH_ROOTS[@]}" \
    | grep -vE '^shedos-' \
    | grep -vE '^(virtualbox-guest-modules-arch|virtualbox-host-modules-arch)$' \
    | LC_ALL=C sort -u > "$TMPDIR/closure.txt"

# The marker. A closure name the manifest also names is one Arch and the
# channel both have, and the channel's is the one a ShedOS box installs. Said
# in the file rather than left to repository order, which is what used to
# decide it.
replaced=0
{
    cat << 'EOF'
# AUTO-GENERATED by tools/resolve-meta-closure.sh; do not edit.
# Full transitive closure of packages/official/*.txt resolved against
# core/extra/multilib. Consumed by tools/render-meta-depends.sh to
# populate shedos-meta's depends=() with every Arch transitive dep
# explicit, so install-time pacstrap has no virtual-provider rolls.
# A name followed by a tab and "replaced" is served by the ShedOS
# channel rather than by Arch, and the renderer emits the release
# manifest's pinned form of it.
# Regenerate: sudo tools/resolve-meta-closure.sh

EOF
    while IFS= read -r p; do
        if [[ -n ${channel_set[$p]:-} ]]; then
            printf '%s\treplaced\n' "$p"
            replaced=$((replaced + 1))
        else
            printf '%s\n' "$p"
        fi
    done < "$TMPDIR/closure.txt"
} > "$OUTPUT_FILE"

TOTAL=$(grep -cv '^#\|^$' "$OUTPUT_FILE")
echo ""
echo "Wrote $OUTPUT_FILE ($TOTAL packages, $replaced replaced by the channel)."

if [ -n "${SUDO_USER:-}" ]; then
    chown "$SUDO_USER:$(id -gn "$SUDO_USER")" "$OUTPUT_FILE"
    echo "Restored ownership to user: $SUDO_USER"
fi

# Report the virtual-provider landscape the closure sits in: for every virtual
# something in the closure depends on, which packages in the repositories
# provide it, and which of those are neither shipped nor named in
# packages/meta-conflicts.txt. That list is what pacstrap could pick from when
# it has a choice — the trap that broke the live-ISO build twice (jack → jack2,
# pipewire-session-manager → pipewire-media-session).
#
# This reports and does not fail, and the reason is worth writing down. What
# stood here before asked pacman to resolve each virtual name and treated the
# answer as the provider set. It is not: `pacman -Sp jack` prints the install
# chain of the one provider pacman picked — alsa-lib, opus, db5.3 and the rest
# — so the "providers" came back as a dependency list, several of them already
# in the closure, and the gate below it never fired. It passed with jack2
# deleted from the conflicts file whose own header names jack2 as its reason
# for existing.
#
# Inverting what every package declares it provides is the honest enumeration,
# and against it the current conflicts list does not pass: sixteen virtuals
# have an alternative nobody has spoken for, and most are alternatives pacman
# would never reach for because the closure already names the provider by
# name — ffmpeg beside ffmpeg4.4, zlib beside zlib-ng-compat. Which of them a
# metapackage should actually forbid changes what installs, and for
# opengl-driver it runs straight into the NVIDIA gate. So this says what it
# sees and the threshold is somebody's decision, not this script's. The
# conflicts file's own contents are pinned by test/meta instead.
echo ""
echo "The virtual-provider landscape..."

[[ -n "$(list_names "$META_CONFLICTS")" ]] \
    || { echo "ERROR: $META_CONFLICTS names nothing." >&2; exit 1; }

# "<package> <name> <name> ..." for every package in core/extra/multilib, once
# for what each provides and once for what each depends on.
expac --sync --config "$TMPDIR/pacman.conf" '%n %P' > "$TMPDIR/provides.txt" \
    || { echo "ERROR: could not read what the repositories provide." >&2; exit 1; }
expac --sync --config "$TMPDIR/pacman.conf" '%n %D' > "$TMPDIR/depends.txt" \
    || { echo "ERROR: could not read what the repositories depend on." >&2; exit 1; }

# Only the names something in the closure depends on. A virtual nothing we
# install asks for is not a choice anybody makes on our behalf.
awk 'NR == FNR { closure[$1] = 1; next }
     $1 in closure {
         for (i = 2; i <= NF; i++) {
             v = $i; sub(/[=<>].*/, "", v)
             if (v != "") print v
         }
     }' "$TMPDIR/closure.txt" "$TMPDIR/depends.txt" | LC_ALL=C sort -u > "$TMPDIR/wanted.txt"

# Inverted: "<name>\t<provider>", every provider the repositories have.
awk 'NR == FNR { want[$1] = 1; next }
     {
         for (i = 2; i <= NF; i++) {
             v = $i; sub(/[=<>].*/, "", v)
             if (v in want) print v "\t" $1
         }
     }' "$TMPDIR/wanted.txt" "$TMPDIR/provides.txt" | LC_ALL=C sort -u \
     > "$TMPDIR/inversion.tsv"

awk -F'\t' '
    FILENAME == ARGV[1] { closure[$1] = 1; next }
    FILENAME == ARGV[2] { if ($0 ~ /^[[:space:]]*(#|$)/) next; forbidden[$1] = 1; next }
    { providers[$1] = providers[$1] " " $2 }
    END {
        multi = 0; unspoken = 0
        for (v in providers) {
            n = split(providers[v], p, " ")
            if (n < 2) continue
            multi++
            shipped = 0; loose = ""
            for (i = 1; i <= n; i++) {
                if (p[i] in closure) shipped++
                else if (!(p[i] in forbidden)) loose = loose " " p[i]
            }
            if (shipped >= 1 && loose != "") {
                unspoken++
                printf "  note %s: %d provider(s), %d shipped, not spoken for:%s\n", v, n, shipped, loose
            }
        }
        printf "  %d virtual(s) with more than one provider; %d carry an alternative nobody has named\n", multi, unspoken
    }' "$TMPDIR/closure.txt" "$META_CONFLICTS" "$TMPDIR/inversion.tsv" | LC_ALL=C sort

echo "=========================================="
